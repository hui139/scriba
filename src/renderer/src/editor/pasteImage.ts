import type { EditorView } from '@codemirror/view'
import { useUI } from '../store/ui'

const IMAGE_EXTENSIONS: Record<string, string> = {
  'image/png': 'png',
  'image/jpeg': 'jpg',
  'image/jpg': 'jpg',
  'image/gif': 'gif',
  'image/webp': 'webp',
  'image/bmp': 'bmp',
  'image/svg+xml': 'svg',
  'image/avif': 'avif'
}

/** The first image file contained in a paste operation, if any. */
export function pastedImageFile(data: DataTransfer | null): File | null {
  if (!data) return null
  for (let index = 0; index < data.items.length; index++) {
    const item = data.items[index]
    if (item.kind === 'file' && item.type.startsWith('image/')) {
      const file = item.getAsFile()
      if (file) return file
    }
  }
  return Array.from(data.files).find((file) => file.type.startsWith('image/')) ?? null
}

/**
 * Save a pasted image next to the document and insert markdown for it. No path has
 * to be typed: the filename is generated by the main process.
 */
export async function insertPastedImage(
  view: EditorView,
  file: File,
  docPath: string | null
): Promise<void> {
  try {
    const extension = IMAGE_EXTENSIONS[file.type] ?? 'png'
    const data = new Uint8Array(await file.arrayBuffer())
    const saved = await window.api.fs.savePastedImage(docPath, data, extension)
    const { from, to } = view.state.selection.main
    // If the image is pasted at the end of a line, start a new line and leave the
    // cursor there, so the image renders immediately instead of showing its source.
    const lineEnd = to === view.state.doc.lineAt(to).to
    const insert = lineEnd ? `![](${saved.markdownPath})\n` : `![](${saved.markdownPath})`
    view.dispatch({
      changes: { from, to, insert },
      selection: { anchor: from + insert.length }
    })
    view.focus()
  } catch (error) {
    useUI.getState().toast(error instanceof Error ? error.message : String(error), 'error')
  }
}
